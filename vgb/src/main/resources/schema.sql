-- Nur zwei Quelltabellen sind zum Entwicklungsstart angeschlossen.
CREATE TABLE ALT_VGBVERTRAG (
    VERTRAG_ID BIGINT NOT NULL,
    DATENSTAND VARCHAR(16) NOT NULL,
    VERTRAGSNUMMER VARCHAR(80),
    TARIF VARCHAR(80),
    BEGINN DATE,
    ABLAUF DATE,
    ZAHLWEISE VARCHAR(80),
    PRIMARY KEY (VERTRAG_ID, DATENSTAND)
);
CREATE TABLE ALT_VGBRISIKO (
    VERTRAG_ID BIGINT NOT NULL,
    DATENSTAND VARCHAR(16) NOT NULL,
    RISIKONUMMER VARCHAR(80),
    RISIKOART VARCHAR(80),
    VERSICHERUNGSSUMME DECIMAL(15,2),
    TARIFIERUNGSZONE VARCHAR(80),
    SELBSTBEHALT DECIMAL(15,2),
    PRIMARY KEY (VERTRAG_ID, DATENSTAND)
);
